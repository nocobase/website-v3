// The search dialog: opens from the header button or Cmd/Ctrl+K, queries the Pagefind index of the page's language, shows results with the matching headings, and is keyboard navigable (arrows, Enter, Escape).
const dialog = document.getElementById('docSearch');
const input = document.getElementById('docSearchInput');
const box = document.getElementById('docSearchResults');
if (dialog && input && box) {
  let pagefind;
  let token = 0;
  let selected = -1;
  const hits = () => [...box.querySelectorAll('a.doc-search-hit')];
  const message = text => { box.innerHTML = ''; const p = document.createElement('p'); p.className = 'doc-search-msg'; p.textContent = text; box.append(p); selected = -1; };
  const select = i => {
    const list = hits();
    if (!list.length) return;
    selected = (i + list.length) % list.length;
    list.forEach((a, n) => a.setAttribute('aria-selected', String(n === selected)));
    list[selected].scrollIntoView({ block: 'nearest' });
  };
  const load = async () => {
    if (!pagefind) {
      // The index is generated by the build, next to the pages; it does not exist in the dev server
      pagefind = await import(/* @vite-ignore */ '/pagefind/pagefind.js');
      await pagefind.options({ baseUrl: '/' });
    }
    return pagefind;
  };
  const open = () => {
    if (!dialog.open) dialog.showModal();
    input.focus();
    input.select();
    if (!input.value) message(dialog.dataset.hint);
    load().catch(() => {});
  };
  const render = async (query, mine) => {
    let pf;
    try { pf = await load(); } catch { message(dialog.dataset.error); return; }
    const search = await pf.search(query);
    const results = await Promise.all(search.results.slice(0, 8).map(r => r.data()));
    if (mine !== token) return;
    if (!results.length) { message(dialog.dataset.empty.replace('{query}', query)); return; }
    box.innerHTML = '';
    for (const r of results) {
      const card = document.createElement('div');
      const main = document.createElement('a');
      main.className = 'doc-search-hit';
      main.href = r.url;
      main.setAttribute('role', 'option');
      const title = document.createElement('b');
      title.append(r.meta.title || r.url);
      const section = r.filters?.section?.[0];
      if (section) { const tag = document.createElement('em'); tag.textContent = section; title.append(tag); }
      const excerpt = document.createElement('p');
      excerpt.innerHTML = r.excerpt;
      main.append(title, excerpt);
      card.append(main);
      const subs = (r.sub_results || []).filter(s => s.url !== r.url && s.anchor).slice(0, 2);
      if (subs.length) {
        const wrap = document.createElement('div');
        wrap.className = 'doc-search-sub';
        for (const s of subs) {
          const a = document.createElement('a');
          a.className = 'doc-search-hit';
          a.href = s.url;
          a.setAttribute('role', 'option');
          const b = document.createElement('b');
          b.append(s.title);
          const p = document.createElement('p');
          p.innerHTML = s.excerpt;
          a.append(b, p);
          wrap.append(a);
        }
        card.append(wrap);
      }
      box.append(card);
    }
    select(0);
  };
  let timer;
  input.addEventListener('input', () => {
    clearTimeout(timer);
    const query = input.value.trim();
    const mine = ++token;
    if (!query) { message(dialog.dataset.hint); return; }
    timer = setTimeout(() => render(query, mine), 120);
  });
  input.addEventListener('keydown', e => {
    if (e.key === 'ArrowDown') { e.preventDefault(); select(selected + 1); }
    else if (e.key === 'ArrowUp') { e.preventDefault(); select(selected - 1); }
    else if (e.key === 'Escape') { e.preventDefault(); dialog.close(); }
    else if (e.key === 'Enter') { const a = hits()[selected]; if (a) { e.preventDefault(); a.click(); } }
  });
  box.addEventListener('mousemove', e => { const a = e.target.closest('a.doc-search-hit'); if (a) select(hits().indexOf(a)); });
  // Clicking the backdrop closes the dialog
  dialog.addEventListener('click', e => { if (e.target === dialog) dialog.close(); });
  dialog.addEventListener('close', () => { input.value = ''; });
  document.addEventListener('click', e => { if (e.target.closest('[data-search-open]')) { e.preventDefault(); open(); document.getElementById('nav')?.classList.remove('open'); } });
  document.addEventListener('keydown', e => {
    if ((e.metaKey || e.ctrlKey) && !e.shiftKey && !e.altKey && e.key.toLowerCase() === 'k') { e.preventDefault(); dialog.open ? dialog.close() : open(); }
    else if (e.key === '/' && !dialog.open && !/^(INPUT|TEXTAREA|SELECT)$/.test(document.activeElement?.tagName ?? '') && !document.activeElement?.isContentEditable) { e.preventDefault(); open(); }
  });
}
